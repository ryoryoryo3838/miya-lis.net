#!/bin/sh
# Fetch BIZ UDMincho and write the stylesheet that serves it from this theme.
#
#   sh fetch-biz-udmincho.sh
#
# The body face is self-hosted rather than linked from fonts.googleapis.com so
# that reading a page needs no request to a third party, which is also what the
# Latin face already does.
#
# A whole Japanese face is several megabytes, far too much to send for one
# page. Google Fonts answers that by cutting the face into slices and giving
# each a `unicode-range`; a browser fetches only the slices holding characters
# the page actually uses — a few hundred kilobytes for ordinary prose. This
# script keeps that arrangement and only moves where the slices are served
# from, renaming them from the opaque hashed names to `<weight>.<n>.woff2`.
#
# BIZ UDMincho is by Morisawa, under the SIL Open Font License 1.1, the same
# licence as Inria Sans. See LICENSES/OFL-1.1.txt.
set -eu

theme_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
out_dir="$theme_dir/fonts/biz-udmincho"
css="$theme_dir/fonts-biz-udmincho.css"

# A modern browser's User-Agent, or the API answers with .ttf and no slicing.
ua='Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36'
api='https://fonts.googleapis.com/css2?family=BIZ+UDMincho:wght@400;700&display=swap'

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

curl -fsS -m 60 -A "$ua" "$api" -o "$work/upstream.css"

mkdir -p "$out_dir"

python3 - "$work/upstream.css" "$out_dir" "$css" <<'PY'
import os, re, sys, urllib.request

upstream, out_dir, css_path = sys.argv[1], sys.argv[2], sys.argv[3]
source = open(upstream, encoding="utf-8").read()

face = re.compile(
    r"@font-face\s*\{(?P<body>[^}]*)\}", re.S)
field = lambda body, name: re.search(
    name + r"\s*:\s*(?P<v>[^;]+);", body).group("v").strip()

# The slice number is the face's position within its weight. Most URLs end in
# `.<n>.woff2` and would give it away, but the last few of each weight — the
# Latin and Cyrillic ranges — are named without one, so count instead.
faces = []
seen = {}
for match in face.finditer(source):
    body = match.group("body")
    weight = field(body, "font-weight")
    url = re.search(r"url\((?P<u>[^)]+)\)", body).group("u").strip("'\"")
    index = seen.get(weight, 0)
    seen[weight] = index + 1
    faces.append((weight, "%03d" % index, url, field(body, "unicode-range")))

for weight, index, url, _ in faces:
    name = "biz-udmincho-%s.%s.woff2" % (weight, index)
    target = os.path.join(out_dir, name)
    if os.path.exists(target):
        continue
    with urllib.request.urlopen(url, timeout=60) as response:
        data = response.read()
    with open(target, "wb") as handle:
        handle.write(data)
    print("fetched", name)

lines = [
    "/* BIZ UDMincho, self-hosted. Generated by fetch-biz-udmincho.sh — edit",
    "   that script, not this file.",
    "",
    "   Morisawa Inc., SIL Open Font License 1.1 (LICENSES/OFL-1.1.txt). The",
    "   face is cut into unicode-range slices so a page fetches only the ones",
    "   holding characters it uses. */",
    "",
]
for weight, index, _, unicode_range in faces:
    lines += [
        "@font-face {",
        "  font-display: swap;",
        "  font-family: 'BIZ UDMincho';",
        "  font-style: normal;",
        "  font-weight: %s;" % weight,
        "  src: url('fonts/biz-udmincho/biz-udmincho-%s.%s.woff2') format('woff2');"
        % (weight, index),
        "  unicode-range: %s;" % unicode_range,
        "}",
        "",
    ]

with open(css_path, "w", encoding="utf-8") as handle:
    handle.write("\n".join(lines))
print("wrote", css_path, "with", len(faces), "faces")
PY
